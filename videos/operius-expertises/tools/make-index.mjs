// Writes index.html (root sequencer) from tools/scenes.json and, when present, assets/sfx/cues.json.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const scenes = JSON.parse(fs.readFileSync(path.join(root, 'tools/scenes.json'), 'utf8'));
const cuesPath = path.join(root, 'assets/sfx/cues.json');
const cues = fs.existsSync(cuesPath) ? JSON.parse(fs.readFileSync(cuesPath, 'utf8')) : [];
const total = Math.max(...scenes.map((s) => s.start + s.dur));
const hosts = scenes
  .map((s, i) => `      <div id="host-${s.id}" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html" data-start="${s.start}" data-duration="${s.dur}" data-track-index="${i}" data-width="1920" data-height="1080"></div>`)
  .join('\n');
// first-fit track assignment: overlapping sounds never share a track (the pad keeps track 19)
const trackEnd = [];
const audio = cues
  .map((c, i) => {
    let tr = c.name === 'pad' ? -1 : trackEnd.findIndex((e) => e <= c.t + 0.0001);
    if (tr === -2 || (tr === -1 && c.name !== 'pad')) { tr = trackEnd.length; trackEnd.push(0); }
    if (c.name !== 'pad') trackEnd[tr] = c.t + c.dur;
    const idx = c.name === 'pad' ? 19 : 20 + tr;
    return `      <audio id="sfx-${i}-${c.name}" src="assets/sfx/${c.file}" data-start="${c.t}" data-duration="${c.dur}" data-track-index="${idx}" data-volume="${c.vol}"></audio>`;
  })
  .join('\n');
const html = `<!doctype html>
<html lang="fr">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="assets/vendor/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #f4f6ff; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; background: #f4f6ff; font-family: Inter, sans-serif; }
    </style>
  </head>
  <body>
    <!-- GENERATED by tools/make-index.mjs — edit tools/scenes/*.mjs and tools/make_sfx.py instead -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">
${hosts}
${audio}
      <div id="fade" style="position:absolute;inset:0;background:#fff;opacity:0;pointer-events:none"></div>
    </div>
    <script>
      // Scenes own their motion (compositions/*.html); the root sequences them, the sound, and the final fade.
      const tl = gsap.timeline({ paused: true });
      tl.fromTo('#fade', { opacity: 0 }, { opacity: 1, duration: 0.9, ease: 'power2.inOut' }, ${total - 0.9});
      window.__timelines['main'] = tl;
    </script>
  </body>
</html>
`;
fs.writeFileSync(path.join(root, 'index.html'), html);
console.log('index.html', scenes.length, 'scenes,', cues.length, 'cues, total', total, 's');
