// Assembles tools/scenes/*.mjs + tools/shared.{css,js} into compositions/<id>.html
// Usage (from project root): node tools/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const sizes = JSON.parse(fs.readFileSync(path.join(root, 'assets/mascot/sizes.json'), 'utf8'));
const sharedCss = fs.readFileSync(path.join(root, 'tools/shared.css'), 'utf8');
const sharedJs = fs.readFileSync(path.join(root, 'tools/shared.js'), 'utf8');

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const h = {
  rng,
  mascot(id, poses, { k = 1.25, x = 0, y = 0 } = {}) {
    const imgs = poses
      .map((p) => {
        const [w, hh] = sizes[p];
        return `<img data-pose="${p}" src="assets/mascot/${p}.png" alt="" style="--w:${Math.round(w * k)}px;--h:${Math.round(hh * k)}px" />`;
      })
      .join('');
    return `<div class="mascot" id="${id}" style="left:${x}px;top:${y}px"><div class="msh"></div><div class="mb">${imgs}</div></div>`;
  },
  particles(seed, n, { w = 1920, hgt = 1080, min = 3, max = 8 } = {}) {
    const r = rng(seed);
    let out = '';
    for (let i = 0; i < n; i++) {
      const s = Math.round(min + r() * (max - min));
      out += `<i class="pt" style="left:${Math.round(r() * w)}px;top:${Math.round(r() * hgt)}px;width:${s}px;height:${s}px"></i>`;
    }
    return out;
  },
  // decor: [{k:'sph'|'warm'|'vio'|'cy'|'ring', x,y,s, a,d,r}]
  decor(list) {
    return list
      .map((o) => {
        const cls = o.k === 'ring' ? 'ring' : 'sph ' + (o.k === 'sph' ? '' : o.k);
        return `<div class="dc ${cls}" data-a="${o.a || 16}" data-d="${o.d || 4}" data-r="${o.r || 0}" style="left:${o.x}px;top:${o.y}px;width:${o.s}px;height:${o.s}px${o.o ? ';opacity:' + o.o : ''}${o.z ? ';z-index:' + o.z : ''}"></div>`;
      })
      .join('');
  },
  title(num, name, tag) {
    return `<div class="tt"><div class="tt-bar grad"></div><div class="mk"><span class="mi tt-name"><span class="gtxt">#${num}</span> — ${name}</span></div><div class="mk"><span class="mi tt-tag">${tag}</span></div></div>`;
  },
  bg(night, blobs) {
    return (
      `<div class="bg${night ? ' night' : ''}"></div>` +
      blobs.map((b) => `<div class="blob ${b.c}" style="left:${b.x}px;top:${b.y}px;width:${b.s}px;height:${b.s}px;opacity:${b.o ?? 0.5}"></div>`).join('')
    );
  },
};

const files = fs
  .readdirSync(path.join(root, 'tools/scenes'))
  .filter((f) => f.endsWith('.mjs'))
  .sort();
fs.mkdirSync(path.join(root, 'compositions'), { recursive: true });
const meta = [];
for (const f of files) {
  const mod = await import(pathToFileURL(path.join(root, 'tools/scenes', f)).href);
  const s = mod.default(h);
  const scope = (css) => css.replace(/\.sc\b/g, '#' + s.id);
  const html = `<!doctype html>
<html lang="fr">
  <head>
    <meta charset="UTF-8" />
  </head>
  <body>
    <!-- GENERATED by tools/build.mjs from tools/scenes/${f} — do not edit by hand -->
    <template>
      <style>
${scope(sharedCss)}
${scope(s.css || '')}
      </style>
      <div id="${s.id}" class="sc" data-composition-id="${s.id}" data-width="1920" data-height="1080">
        <div class="portal"><div class="cam"><div class="rig">
${s.html}
        </div></div>${s.top || ''}</div>
      </div>
      <script>
(() => {
  const R = document.getElementById('${s.id}');
  const D = ${s.dur};
  const tl = gsap.timeline({ paused: true });
${sharedJs}
${s.js}
  window.__timelines['${s.id}'] = tl;
})();
      </script>
    </template>
  </body>
</html>
`;
  fs.writeFileSync(path.join(root, 'compositions', s.id + '.html'), html);
  meta.push({ id: s.id, start: s.start, dur: s.dur });
}
fs.writeFileSync(path.join(root, 'tools/scenes.json'), JSON.stringify(meta, null, 2));
console.log('built', meta.map((m) => m.id).join(', '));
